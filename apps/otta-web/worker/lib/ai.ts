/** `CFAI_<PROVIDER>_API_KEY`, matching the existing Cloudflare-AI demo env convention. */
function platformProviderKey(env: CloudflareEnv, provider: string | null): string | undefined {
    if (!provider) return undefined;
    const key = `CFAI_${provider.toUpperCase().replace(/-/g, '_')}_API_KEY`;
    return (env as unknown as Record<string, string | undefined>)[key];
}

/**
 * The OPERATOR-ONLY transport bag: values that decide WHERE a request goes.
 *
 * FROM ENV, NOT FROM `features.ottaai`. `config.loader` exports the whole `features.ottaai`
 * object to the CLIENT as `OTTAAI_CONFIG`, and this bag can legitimately carry request
 * headers — so putting it in the config file would ship an operator header set to every
 * browser. Env keeps it server-side, alongside `CFAI_GATEWAY_TOKEN` and the provider keys.
 *
 * Today only Azure OpenAI needs it: its gateway path is
 * `/azure-openai/{resource}/{deployment}/chat/completions?api-version=…`, and WITHOUT these
 * three values the transport reports Azure as unservable — the settings form then stops
 * offering it, instead of accepting a real tenant key for calls that can never route.
 *
 * Extending: add the provider's operator-only keys here and to `.env.example`. Anything a
 * TENANT may set belongs on the credential's own `transportConfig`, which the merge filters
 * against the registry's `destinationKeys`.
 */
function platformTransportConfig(env: CloudflareEnv): Record<string, unknown> | undefined {
    const read = (key: string) => (env as unknown as Record<string, string | undefined>)[key]?.trim() || undefined;

    const bag: Record<string, unknown> = {};
    const resourceName = read('CFAI_AZURE_RESOURCE_NAME');
    const deploymentName = read('CFAI_AZURE_DEPLOYMENT_NAME');
    const apiVersion = read('CFAI_AZURE_API_VERSION');
    // ALL THREE OR NONE — a partial Azure config builds no URL, so treating it as configured
    // would put Azure back in the form and reproduce exactly the bug this closes.
    if (resourceName && deploymentName && apiVersion) {
        Object.assign(bag, { resourceName, deploymentName, apiVersion });
    }

    return Object.keys(bag).length > 0 ? bag : undefined;
}

