/**
 * Build the keyring from env.
 *
 * `AI_CREDENTIAL_KEYRING` is a JSON map `{"<keyId>": "<base64 secret>"}` and
 * `AI_CREDENTIAL_KEY_ID` names the write key — that pair is what makes ROTATION possible
 * (single → dual → drain → retire). `AI_CREDENTIAL_SECRET` is the single-key convenience
 * for a first deploy and is equivalent to `{"k1": "<secret>"}` with `currentKeyId: 'k1'`.
 *
 * Generate with a CSPRNG, never type one:  `openssl rand -base64 48`
 */
export function buildAiKeyring(env: CloudflareEnv): Keyring | null {
    const raw = (env as unknown as Record<string, string | undefined>).AI_CREDENTIAL_KEYRING;
    if (raw) {
        let keys: Record<string, string>;
        try {
            keys = JSON.parse(raw) as Record<string, string>;
        } catch {
            throw new Error('AI_CREDENTIAL_KEYRING is not valid JSON. Expected {"<keyId>": "<base64 secret>"}.');
        }
        const currentKeyId =
            (env as unknown as Record<string, string | undefined>).AI_CREDENTIAL_KEY_ID ?? Object.keys(keys)[0];
        if (!currentKeyId) throw new Error('AI_CREDENTIAL_KEYRING is empty.');
        return createKeyring({ keys, currentKeyId });
    }

    const single = (env as unknown as Record<string, string | undefined>).AI_CREDENTIAL_SECRET;
    if (!single) return null;
    return createKeyring({ keys: { k1: single }, currentKeyId: 'k1' });
}

