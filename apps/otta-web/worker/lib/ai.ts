/**
 * A task's GATE STRENGTH is the entire commercial argument of BYOK, and it is a property
 * of the TASK rather than of the plan: a free user WITH a key gets the premium path, and a
 * paying user WITHOUT one does not.
 *
 *  • `soft`     — cheap work where the platform floor is good enough; BYOK is the upsell.
 *  • `required` — the tenant's own key, or the feature is blocked. Use where the free
 *                 floor is not accurate enough to ship under the brand and premium
 *                 inference for every free user is not funded.
 */
export const AI_TASKS = {
    /** General assistant text. Runs free on the platform model. */
    assist: 'assist',
    /** Summarise a blog post or a long document. */
    summarize: 'summarize',
    /** Long-document extraction — expensive, tenant-key only. */
    extract: 'extract',
    /** Vectorise text for semantic search, similarity and recommendations. */
    embed: 'embed',
} as const;

export type AiTaskKey = (typeof AI_TASKS)[keyof typeof AI_TASKS];

const TASK_POLICIES: AiTaskPolicy[] = [
    {
        key: AI_TASKS.assist,
        label: 'Assistant',
        gate: 'soft',
    },
    {
        key: AI_TASKS.summarize,
        label: 'Summarise',
        gate: 'soft',
        // Cheap text work. The tenant is paying when they bring a key, so their model wins.
        modelPolicy: 'tenant-preferred',
    },
    {
        key: AI_TASKS.extract,
        label: 'Document extraction',
        // NARROWING ONLY. app `auto` ∧ task `byok` ⇒ `byok`: the gate lives in the
        // RESOLVER, not the browser.
        mode: 'byok',
        gate: 'required',
        // NO `requiredCapabilities: ['vision']` — DELIBERATE, do not "restore" it.
        //
        // @ottabase/ottaai's call contract is TEXT CHAT: `AiCallOptions` message content is
        // a plain string, so there is no way to actually send an image. Requiring `vision`
        // therefore filtered out perfectly usable text credentials in exchange for a
        // capability this route cannot exercise — a stricter gate that buys nothing and
        // blocks tenants whose key would have worked.
        //
        // If multimodal content types are ever added to `AiCallOptions`, add the requirement
        // back in the SAME change.
    },
    {
        key: AI_TASKS.embed,
        label: 'Embeddings',
        // The shipped AI Gateway embedding wire is deliberately OpenAI-only. Pinning the
        // model does two useful things at once: an OpenAI tenant key can serve embeddings
        // even when its chat default is GPT, and a non-OpenAI credential is filtered out
        // before a call carrying that credential reaches a provider-specific endpoint.
        modelPolicy: 'task-pinned',
        pinnedModels: { openai: 'text-embedding-3-small' },
        // This is also the platform-path model. A deployment using a non-OpenAI platform
        // provider remains configured for chat, but the transport refuses embedding calls
        // explicitly rather than guessing at another provider's wire format.
        defaultModel: 'openai/text-embedding-3-small',
        requiredCapabilities: ['embedding'],
    },
];

